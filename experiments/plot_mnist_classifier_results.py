"""Plot aggregate MNIST conditional-generation classifier metrics.

Example:
    python -m experiments.plot_mnist_classifier_results \
      --results artifacts/transition_comparison/mnist/classifier_eval_equal_n100.json \
      --output docs/images/mnist-transition-comparison.png
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np


ORDER = ("uniform", "gaussian", "absorbing")


def plot_results(results_path, output):
    """Plot mean ± sample standard deviation across seeds for two metrics.

    Args:
        results_path: JSON generated by ``evaluate_mnist_classifier.py``.
        output: Destination PNG path.
    """
    results = json.loads(Path(results_path).read_text())
    grouped = defaultdict(list)
    for result in results:
        grouped[result["transition"]].append(result)
    classifier_accuracy = results[0]["classifier_test_accuracy"]
    metrics = (
        ("target_accuracy", "Requested-label accuracy"),
        ("mean_target_probability", "Mean requested-label probability"),
    )
    colors = {"uniform": "#1f77b4", "gaussian": "#ff7f0e", "absorbing": "#2ca02c"}
    fig, axes = plt.subplots(1, 2, figsize=(9, 4.2), sharey=True)
    x = np.arange(len(ORDER))
    for axis, (key, title) in zip(axes, metrics):
        means = [np.mean([row[key] for row in grouped[name]]) for name in ORDER]
        stds = [np.std([row[key] for row in grouped[name]], ddof=1) for name in ORDER]
        axis.bar(x, means, yerr=stds, capsize=5, color=[colors[name] for name in ORDER])
        for index, name in enumerate(ORDER):
            seed_values = [row[key] for row in grouped[name]]
            axis.scatter(
                np.full(len(seed_values), index), seed_values, color="black",
                s=18, zorder=3,
            )
            axis.text(index, means[index] + stds[index] + 0.02, f"{means[index]:.3f}",
                      ha="center", va="bottom", fontsize=9)
        axis.set_xticks(x, ORDER)
        axis.set_ylim(0, 1.08)
        axis.set_title(title)
        axis.grid(axis="y", alpha=0.25)
    axes[0].set_ylabel("Classifier score")
    fig.suptitle(
        f"MNIST conditional generation (3 seeds; classifier test accuracy {classifier_accuracy:.3f})"
    )
    fig.tight_layout()
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output, dpi=180)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", required=True)
    parser.add_argument("--output", default="docs/images/mnist-transition-comparison.png")
    args = parser.parse_args()
    plot_results(args.results, args.output)
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
